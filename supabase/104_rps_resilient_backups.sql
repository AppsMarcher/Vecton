create or replace function public.rps_capture_backup(
  p_organization_id uuid,
  p_ano integer,
  p_mes integer,
  p_kind text,
  p_created_by uuid default null,
  p_source_restore_id uuid default null
)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_snapshot public.rps_snapshots%rowtype;
  v_run_id uuid := gen_random_uuid();
  v_hash text;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'rps_capture_backup exige service_role';
  end if;
  if p_kind not in ('scheduled', 'manual', 'pre_restore') then
    raise exception 'Tipo de backup invalido';
  end if;

  if p_kind <> 'pre_restore' then
    lock table public.rps_snapshots in share mode;
    lock table storage.objects in share mode;
    begin
      insert into public.rps_maintenance_locks (
        organization_id, ano, mes, backup_run_id, lock_reason, locked_by
      ) values (
        p_organization_id, p_ano, p_mes, v_run_id, 'backup', p_created_by
      );
    exception when unique_violation then
      raise exception 'Periodo temporariamente bloqueado por outra operacao';
    end;
  end if;

  select * into v_snapshot
  from public.rps_snapshots
  where organization_id = p_organization_id and ano = p_ano and mes = p_mes
  for share;

  if not found then
    raise exception 'Snapshot RPS %/% nao encontrado', p_mes, p_ano;
  end if;

  v_hash := encode(digest(convert_to(v_snapshot.payload::text, 'UTF8'), 'sha256'), 'hex');

  insert into public.rps_backup_runs (
    id, organization_id, ano, mes, kind, status, retention_until,
    source_version, source_updated_at, snapshot_hash, storage_prefix,
    created_by, source_restore_id
  ) values (
    v_run_id, p_organization_id, p_ano, p_mes, p_kind, 'building',
    now() + interval '6 months', v_snapshot.version, v_snapshot.updated_at,
    v_hash,
    v_run_id::text || '/' || p_organization_id::text || '/' ||
      p_ano::text || '-' || lpad(p_mes::text, 2, '0'),
    p_created_by, p_source_restore_id
  );

  insert into public.rps_backup_snapshots (
    run_id, payload, source_version, source_updated_at, snapshot_hash
  ) values (
    v_run_id, v_snapshot.payload, v_snapshot.version, v_snapshot.updated_at, v_hash
  );

  return v_run_id;
end;
$$;

create or replace function public.rps_start_restore(
  p_organization_id uuid,
  p_ano integer,
  p_mes integer,
  p_backup_run_id uuid,
  p_initiated_by uuid
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_run public.rps_backup_runs%rowtype;
  v_restore_id uuid := gen_random_uuid();
  v_current_version bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'rps_start_restore exige service_role';
  end if;

  select * into v_run from public.rps_backup_runs
  where id = p_backup_run_id for share;
  if not found or v_run.organization_id <> p_organization_id
    or v_run.ano <> p_ano or v_run.mes <> p_mes
    or v_run.status <> 'ready' or v_run.retention_until <= now() then
    raise exception 'Backup indisponivel para este periodo';
  end if;

  lock table public.rps_snapshots in share mode;
  lock table storage.objects in share mode;

  delete from public.rps_maintenance_locks
  where organization_id = p_organization_id and ano = p_ano and mes = p_mes
    and expires_at <= now();

  select version into v_current_version from public.rps_snapshots
  where organization_id = p_organization_id and ano = p_ano and mes = p_mes;

  insert into public.rps_restore_operations (
    id, organization_id, ano, mes, backup_run_id, initiated_by,
    target_version_before
  ) values (
    v_restore_id, p_organization_id, p_ano, p_mes, p_backup_run_id,
    p_initiated_by, v_current_version
  );

  begin
    insert into public.rps_maintenance_locks (
      organization_id, ano, mes, restore_id, lock_reason, locked_by
    ) values (
      p_organization_id, p_ano, p_mes, v_restore_id, 'restore', p_initiated_by
    );
  exception when unique_violation then
    delete from public.rps_restore_operations where id = v_restore_id;
    raise exception 'Ja existe uma restauracao em andamento para este periodo';
  end;

  return v_restore_id;
end;
$$;

create or replace function public.rps_apply_restore_snapshot(p_restore_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_op public.rps_restore_operations%rowtype;
  v_backup public.rps_backup_snapshots%rowtype;
  v_hash text;
  v_version bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'rps_apply_restore_snapshot exige service_role';
  end if;

  select * into v_op from public.rps_restore_operations
  where id = p_restore_id for update;
  if not found or v_op.status not in ('preparing', 'running') then
    raise exception 'Operacao de restauracao invalida';
  end if;

  select * into v_backup from public.rps_backup_snapshots
  where run_id = v_op.backup_run_id;
  if not found then raise exception 'Snapshot do backup nao encontrado'; end if;

  v_hash := encode(digest(convert_to(v_backup.payload::text, 'UTF8'), 'sha256'), 'hex');
  if v_hash <> v_backup.snapshot_hash then
    raise exception 'Hash do snapshot de backup invalido';
  end if;

  insert into public.rps_snapshots (
    organization_id, ano, mes, payload, version, created_by, updated_by
  ) values (
    v_op.organization_id, v_op.ano, v_op.mes, v_backup.payload, 1,
    v_op.initiated_by, v_op.initiated_by
  )
  on conflict (organization_id, ano, mes) do update
  set payload = excluded.payload,
      version = public.rps_snapshots.version + 1,
      updated_by = v_op.initiated_by
  returning version into v_version;

  update public.rps_restore_operations
  set status = 'running', phase = 'database_applied', target_version_after = v_version
  where id = p_restore_id;
  return v_version;
end;
$$;

create or replace function public.rps_rollback_restore_snapshot(p_restore_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_op public.rps_restore_operations%rowtype;
  v_backup public.rps_backup_snapshots%rowtype;
  v_hash text;
  v_version bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'rps_rollback_restore_snapshot exige service_role';
  end if;
  select * into v_op from public.rps_restore_operations where id = p_restore_id for update;
  if not found or v_op.safety_backup_run_id is null then
    raise exception 'Backup de seguranca nao encontrado';
  end if;
  select * into v_backup from public.rps_backup_snapshots
  where run_id = v_op.safety_backup_run_id;
  if not found then raise exception 'Snapshot de seguranca nao encontrado'; end if;
  v_hash := encode(digest(convert_to(v_backup.payload::text, 'UTF8'), 'sha256'), 'hex');
  if v_hash <> v_backup.snapshot_hash then raise exception 'Hash do snapshot de seguranca invalido'; end if;

  insert into public.rps_snapshots (
    organization_id, ano, mes, payload, version, created_by, updated_by
  ) values (
    v_op.organization_id, v_op.ano, v_op.mes, v_backup.payload, 1,
    v_op.initiated_by, v_op.initiated_by
  )
  on conflict (organization_id, ano, mes) do update
  set payload = excluded.payload,
      version = public.rps_snapshots.version + 1,
      updated_by = v_op.initiated_by
  returning version into v_version;
  return v_version;
end;
$$;

create or replace function public.rps_finish_restore(
  p_restore_id uuid,
  p_status text,
  p_phase text,
  p_error_message text default null,
  p_rollback_error text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'rps_finish_restore exige service_role';
  end if;
  if p_status not in ('succeeded', 'failed', 'rolled_back', 'rollback_failed') then
    raise exception 'Status final invalido';
  end if;
  update public.rps_restore_operations
  set status = p_status, phase = p_phase, error_message = p_error_message,
      rollback_error = p_rollback_error, finished_at = now()
  where id = p_restore_id;
  delete from public.rps_maintenance_locks where restore_id = p_restore_id;
end;
$$;

create or replace function public.rps_reject_write_while_locked()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_org uuid := case when tg_op = 'DELETE' then old.organization_id else new.organization_id end;
  v_ano integer := case when tg_op = 'DELETE' then old.ano else new.ano end;
  v_mes integer := case when tg_op = 'DELETE' then old.mes else new.mes end;
begin
  if coalesce(auth.role(), '') = 'service_role' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;
  if exists (
    select 1 from public.rps_maintenance_locks
    where organization_id = v_org and ano = v_ano and mes = v_mes and expires_at > now()
  ) then
    raise exception using
      errcode = '55006',
      message = 'RPS_LOCKED_FOR_RESTORE',
      detail = 'Este periodo esta temporariamente bloqueado para restauracao.';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists trg_rps_snapshots_restore_lock on public.rps_snapshots;
create trigger trg_rps_snapshots_restore_lock
before insert or update or delete on public.rps_snapshots
for each row execute function public.rps_reject_write_while_locked();

create or replace function public.rps_attachment_period_unlocked(object_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = public, storage
as $$
declare
  v_parts text[] := storage.foldername(object_name);
  v_org uuid;
  v_ano integer;
  v_mes integer;
begin
  if coalesce(auth.role(), '') = 'service_role' then return true; end if;
  if array_length(v_parts, 1) < 2
    or v_parts[1] !~ '^[0-9a-fA-F-]{36}$'
    or v_parts[2] !~ '^\d{4}-\d{2}$' then
    return false;
  end if;
  v_org := v_parts[1]::uuid;
  v_ano := split_part(v_parts[2], '-', 1)::integer;
  v_mes := split_part(v_parts[2], '-', 2)::integer;
  return not exists (
    select 1 from public.rps_maintenance_locks
    where organization_id = v_org and ano = v_ano and mes = v_mes and expires_at > now()
  );
end;
$$;

