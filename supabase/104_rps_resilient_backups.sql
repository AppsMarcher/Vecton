create table if not exists public.rps_backup_runs (
  id                  uuid primary key default gen_random_uuid(),
  organization_id     uuid not null references public.organizations(id) on delete cascade,
  ano                 integer not null check (ano between 2000 and 2200),
  mes                 integer not null check (mes between 1 and 12),
  kind                text not null check (kind in ('scheduled', 'manual', 'pre_restore')),
  status              text not null default 'building' check (status in ('building', 'ready', 'failed', 'expired')),
  captured_at         timestamptz not null default now(),
  completed_at        timestamptz,
  retention_until     timestamptz not null default (now() + interval '6 months'),
  source_version      bigint not null,
  source_updated_at   timestamptz,
  snapshot_hash       text not null,
  storage_prefix      text not null unique,
  expected_file_count integer not null default 0 check (expected_file_count >= 0),
  verified_file_count integer not null default 0 check (verified_file_count >= 0),
  expected_bytes      bigint not null default 0 check (expected_bytes >= 0),
  verified_bytes      bigint not null default 0 check (verified_bytes >= 0),
  created_by          uuid references auth.users(id) on delete set null,
  source_restore_id   uuid,
  error_message       text,
  metadata            jsonb not null default '{}'::jsonb
);

create index if not exists rps_backup_runs_period_idx
  on public.rps_backup_runs (organization_id, ano, mes, captured_at desc);
create index if not exists rps_backup_runs_retention_idx
  on public.rps_backup_runs (retention_until)
  where status in ('ready', 'failed');

create table if not exists public.rps_backup_snapshots (
  run_id              uuid primary key references public.rps_backup_runs(id) on delete cascade,
  payload             jsonb not null,
  source_version      bigint not null,
  source_updated_at   timestamptz,
  snapshot_hash       text not null,
  created_at          timestamptz not null default now()
);

create table if not exists public.rps_backup_files (
  id                  bigint generated by default as identity primary key,
  run_id              uuid not null references public.rps_backup_runs(id) on delete cascade,
  original_path       text not null,
  backup_path         text not null,
  size_bytes          bigint not null check (size_bytes >= 0),
  sha256              text not null,
  content_type        text,
  created_at          timestamptz not null default now(),
  unique (run_id, original_path),
  unique (backup_path)
);

create index if not exists rps_backup_files_run_idx
  on public.rps_backup_files (run_id);

create table if not exists public.rps_restore_operations (
  id                    uuid primary key default gen_random_uuid(),
  organization_id       uuid not null references public.organizations(id) on delete cascade,
  ano                   integer not null check (ano between 2000 and 2200),
  mes                   integer not null check (mes between 1 and 12),
  backup_run_id         uuid not null references public.rps_backup_runs(id),
  safety_backup_run_id  uuid references public.rps_backup_runs(id),
  status                text not null default 'preparing'
                          check (status in ('preparing', 'running', 'succeeded', 'failed', 'rolled_back', 'rollback_failed')),
  phase                 text not null default 'lock_acquired',
  initiated_by          uuid not null references auth.users(id) on delete restrict,
  started_at            timestamptz not null default now(),
  finished_at           timestamptz,
  target_version_before bigint,
  target_version_after  bigint,
  files_replaced        integer not null default 0,
  bytes_replaced        bigint not null default 0,
  error_message         text,
  rollback_error        text,
  details               jsonb not null default '{}'::jsonb
);

create index if not exists rps_restore_operations_period_idx
  on public.rps_restore_operations (organization_id, ano, mes, started_at desc);

create table if not exists public.rps_maintenance_locks (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  ano             integer not null,
  mes             integer not null,
  restore_id      uuid unique references public.rps_restore_operations(id) on delete cascade,
  backup_run_id   uuid unique,
  lock_reason     text not null check (lock_reason in ('backup', 'restore')),
  locked_by       uuid references auth.users(id) on delete restrict,
  locked_at       timestamptz not null default now(),
  expires_at      timestamptz not null default (now() + interval '2 hours'),
  primary key (organization_id, ano, mes),
  check (num_nonnulls(restore_id, backup_run_id) = 1)
);

alter table public.rps_backup_runs enable row level security;
