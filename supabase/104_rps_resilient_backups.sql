create or replace function public.is_rps_admin(target_organization_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.get_my_access_role(target_organization_id) in ('admin', 'super_admin')
$$;

grant execute on function public.is_rps_admin(uuid) to authenticated;

drop policy if exists "rps admins read backup runs" on public.rps_backup_runs;
create policy "rps admins read backup runs"
on public.rps_backup_runs for select to authenticated
using (public.is_rps_admin(organization_id));

