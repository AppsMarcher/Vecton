-- ============================================================================
-- Mapeamento conta→linha da DRE Gerencial + Custo MO (Headcount).
--
-- Gerado por script a partir de DRE_GER_ACCOUNT_MAP e HC_PESSOAL_ACCOUNTS
-- (app.js) — não retranscrito à mão (626 códigos; risco de erro manual alto
-- demais pra um número que alimenta EBITDA/MC1/CPV/GGF/Custo MO). Fonte de
-- verdade continua sendo app.js; se DRE_GER_ACCOUNT_MAP ou HC_PESSOAL_ACCOUNTS
-- mudar lá, esta tabela precisa ser regerada e uma nova migration aplicada —
-- é uma duplicação deliberada (RPC não pode depender de constante só-JS),
-- documentada aqui pra não ser esquecida.
--
-- line_key usados: receita_bruta, impostos, devolucoes, descontos (compõem
-- receitaLiquida), materiais, custos_pessoal, demais_ggf, custo_absorcao
-- (compõem CPV/lucroBruto), comissoes, demais_desp_comerciais, desp_admin,
-- outros_resultados (compõem EBITDA), hc_pessoal (Custo MO — classificação
-- PRÓPRIA do Headcount, diferente de custos_pessoal: só 47 dos 104 códigos
-- se sobrepõem, confirmado por comparação de conjuntos antes de escrever
-- esta migration).
-- ============================================================================
create table if not exists public.dre_gerencial_account_lines (
  account_number text not null,
  line_key       text not null check (line_key in (
                   'receita_bruta', 'impostos', 'devolucoes', 'descontos',
                   'materiais', 'custos_pessoal', 'demais_ggf', 'custo_absorcao',
                   'comissoes', 'demais_desp_comerciais', 'desp_admin', 'outros_resultados',
                   'hc_pessoal'
                 )),
  primary key (account_number, line_key)
);

create index if not exists idx_dre_gerencial_account_lines_line on public.dre_gerencial_account_lines (line_key);

-- Referência de chart-of-accounts, não tem organization_id (mesma premissa
-- implícita de DRE_GER_ACCOUNT_MAP em app.js — 1 mapeamento pra toda a base,
-- sem multi-tenant real hoje). Leitura pra qualquer autenticado; escrita só
-- por migration/service_role (sem policy de insert/update/delete pro cliente).
alter table public.dre_gerencial_account_lines enable row level security;
drop policy if exists "authenticated read dre_gerencial_account_lines" on public.dre_gerencial_account_lines;
create policy "authenticated read dre_gerencial_account_lines"
on public.dre_gerencial_account_lines for select
using (auth.uid() is not null);

