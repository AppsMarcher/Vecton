const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname,'../src/modules/messages/messagesModule.js'),'utf8');
const start = source.indexOf('    function aplicarTemaEm(');
const end = source.indexOf('    function aplicarTemaMessenger',start);
const defaults = { corLinha:'#4f7cff', corTexto:'#e8edf8', corFundo:'#000000' };
const context = { AJUSTES_PADRAO:defaults, _ajustes:defaults };
vm.createContext(context);
vm.runInContext(source.slice(start,end),context);
const element = () => ({ style: { setProperty(name,value){this[name]=value;} } });
const normal = element();
context.aplicarTemaEm(normal);
assert.equal(normal.style.backgroundColor,'var(--theme-surface, #000000)');
assert.equal(normal.style.color,'var(--theme-ink, #e8edf8)');
const custom = { corLinha:'#123456',corTexto:'#eeeeee',corFundo:'#112233' };
const personalized = element();
context.aplicarTemaEm(personalized,custom);
assert.equal(personalized.style.backgroundColor,custom.corFundo);
assert.equal(personalized.style.color,custom.corTexto);
assert.equal(personalized.style['--line'],custom.corLinha);
assert.equal(custom.corFundo,'#112233');
const customBorder = element();
context.aplicarTemaEm(customBorder,{...defaults,corLinha:'#123456'});
assert.equal(customBorder.style['--line'],'#123456');
assert.equal(customBorder.style.backgroundColor,'var(--theme-surface, #000000)');
console.log('Messenger appearance: default follows app tokens; custom palette remains unchanged.');
