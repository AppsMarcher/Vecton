const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const XLSX=require(process.env.BP_XLSX_TEST_LIB||'../artifacts/bp-test-deps/node_modules/xlsx');
const window={};vm.runInNewContext(fs.readFileSync('src/modules/balance/bpModel.js','utf8'),{window});
const M=window.VECTON_BP_MODEL;
const source=JSON.parse(fs.readFileSync('artifacts/bp/source-plan.json','utf8'));
const plan=source.map(n=>({id:n.code,account_code:n.code,node_class:n.type==='ANALITICA'?'Analitica':'Sintetica',name:n.name,group_key:n.group_key||null,active:true}));
const matrix=[Array.from(M.headers),...source.map(n=>[n.code,n.name,n.type==='ANALITICA'?0:99999999,n.type,n.group_key])];
const first=matrix.findIndex((r,i)=>i&&r[3]==='ANALITICA');matrix[first][2]='1.234,56';
const rows=M.parse(matrix,plan);assert.equal(rows.length,114);assert.equal(rows[0].amount,1234.56);
assert.equal(rows.reduce((s,r)=>s+r.amount,0),1234.56);assert.equal(rows.some(r=>r.account_id==='1'),false);
const clone=()=>structuredClone(matrix);
let invalid=clone();invalid.push(invalid[first]);assert.throws(()=>M.parse(invalid,plan),/duplicada/);
invalid=clone();invalid.splice(first,1);assert.equal(M.parse(invalid,plan).length,113);
invalid=clone();invalid[first][0]='9.9.9';assert.throws(()=>M.parse(invalid,plan),/inexistente/);
invalid=clone();invalid[first][3]='SINTETICA';assert.throws(()=>M.parse(invalid,plan),/tipo da conta/);
invalid=clone();invalid[first][4]='Chave diferente';assert.throws(()=>M.parse(invalid,plan),/chave agrupadora/);
invalid=clone();invalid[1][4]='Chave sintética';assert.throws(()=>M.parse(invalid,plan),/sintética não pode/);
invalid=clone();invalid[first][2]=null;assert.throws(()=>M.parse(invalid,plan),/saldo/);
const minimal=matrix.map(r=>[r[0],r[2]]);minimal[0]=['CONTA','SALDO'];assert.equal(M.parse(minimal,plan).length,114);
const book=XLSX.utils.book_new();XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([['Balancete acumulado'],[],...matrix]),'Balancete Setembro');
XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([['Observações']]),'Instruções');
assert.equal(M.parseWorkbook(book,plan,XLSX).length,114);
// Sintéticas sem resultado de fórmula não são usadas; analíticas exigem resultado salvo.
book.Sheets['Balancete Setembro'].C4={t:'n',f:'1+1'};assert.equal(M.parseWorkbook(book,plan,XLSX).length,114);
book.Sheets['Balancete Setembro']['C'+(first+3)]={t:'n',f:'1+1'};assert.throws(()=>M.parseWorkbook(book,plan,XLSX),/Recalcule/);
const two=XLSX.utils.book_new();XLSX.utils.book_append_sheet(two,XLSX.utils.aoa_to_sheet(matrix),'A');XLSX.utils.book_append_sheet(two,XLSX.utils.aoa_to_sheet(matrix),'B');
assert.throws(()=>M.parseWorkbook(two,plan,XLSX),/mais de uma aba/);
console.log('BP balancete: all 173 source accounts, only 114 analytical balances, arbitrary sheet/header, keys, duplicates, optional accounts and formulas OK');

assert.equal(M.parse([M.headers,matrix[first]],plan).length,1);
assert.throws(()=>M.parse([M.headers,matrix[1]],plan),/não contém saldos/);
